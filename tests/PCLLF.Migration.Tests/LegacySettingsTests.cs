            Engine = new LegacySettingsEngine<Instance, Entry, Plan>(() => Entries, () => this, () => new Plan(), new LegacySettingsHost<Instance> {
                InstancePath = instance => instance.Path, Identify = () => "synthetic-device", RegistryFolder = () => "LivingPCL",
                ReadIni = (file, key, fallback) => Ini.TryGetValue((file, key), out string? value) ? value : fallback,
