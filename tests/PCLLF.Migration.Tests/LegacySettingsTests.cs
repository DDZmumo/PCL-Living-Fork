    private sealed class Store : ILegacySettingsStore {
#pragma warning disable CA1416 // Inert RegistryValueKind metadata only.
        public readonly Dictionary<string, (object Value, RegistryValueKind Kind)> Values = new(StringComparer.Ordinal);
#pragma warning restore CA1416
        public readonly List<string> Writes = new();
        public string? FailAfterSetOnce, FailAfterDeleteOnce;
        public string[]? WritesBeforeFailure;
#pragma warning disable CA1416 // Inert RegistryValueKind metadata only.
        public object? GetValue(string name, object? defaultValue = null, bool doNotExpandEnvironmentNames = false) => Values.TryGetValue(name, out var item) ? item.Value : defaultValue;
        public RegistryValueKind GetValueKind(string name) => Values[name].Kind;
#pragma warning restore CA1416
        public void SetValue(string name, object value, RegistryValueKind kind) {
#pragma warning disable CA1416 // Inert RegistryValueKind metadata only.
            Values[name] = (value, kind); Writes.Add(name);
#pragma warning restore CA1416
            if (name == FailAfterSetOnce) { FailAfterSetOnce = null; WritesBeforeFailure = Writes.ToArray(); throw new InvalidOperationException("synthetic set failure"); }
        }
        public void DeleteValue(string name, bool throwOnMissingValue) {
#pragma warning disable CA1416 // Inert RegistryValueKind metadata only.
            Values.Remove(name);
#pragma warning restore CA1416
            if (name == FailAfterDeleteOnce) { FailAfterDeleteOnce = null; throw new InvalidOperationException("synthetic deletion failure"); }
        }
        public void Dispose() { }
    }
    private static void Equal<T>(T expected, T actual) {
        if (!Equals(expected, actual)) throw new Exception($"Expected {expected}, got {actual}.");
    }
    private static void Sequence<T>(IEnumerable<T> expected, IEnumerable<T> actual) {
        if (!expected.SequenceEqual(actual)) throw new Exception("Sequence mismatch.");
    }
    private static void Throws<T>(Action action) where T : Exception {
        try { action(); } catch (T) { return; }
        throw new Exception("Expected " + typeof(T).Name);
    }
