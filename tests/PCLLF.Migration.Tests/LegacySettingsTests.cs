    private static void DesWireFormat() {
        // Independent OpenSSL 3 DES-CBC/PKCS7 output, using the literal LF IV
        // UTF8("95168702") and old key bytes. These are fixed input/output
        // fixtures, not encryption generated by the production method under test.
        // null key: ASCII "@;$ Abv2". Empty key: stable hash 12218072394304329258 -> "12218072".
        // "PCLsynthetic-device": stable hash 11822917189041074307 -> "11822917".
        (string Plain, string? Key, string Cipher)[] vectors = [
            ("", null, "Z2rkugz11VI="),
            ("synthetic-user", null, "easpyrFDg8NjmwbSatOV+g=="),
            ("synthetic-user", "", "yVKVR2ckWDXyfsNYInb5MQ=="),
            ("{\"fixture\":\"非真实账号\",\"empty\":\"\"}", "PCLsynthetic-device", "U3h0tfLTk5jVI51OcO6CLWlEmQLUs/4kX0EOL0l6KuBKJ0jt5HEudtHi/lecGoib")
        ];
        CultureInfo original = CultureInfo.CurrentCulture;
        try {
            foreach (string culture in new[] { "en-US", "fr-FR" }) {
                CultureInfo.CurrentCulture = CultureInfo.GetCultureInfo(culture);
                foreach ((string plain, string? key, string cipher) in vectors) {
                    Equal(cipher, LegacySettingsCrypto.Encrypt(plain, key));
                    Equal(plain, LegacySettingsCrypto.Decrypt(cipher, key));
                }
            }
        } finally { CultureInfo.CurrentCulture = original; }
        Throws<FormatException>(() => LegacySettingsCrypto.Decrypt("*invalid-base64*", "PCLsynthetic-device"));
    }
    private static void CacheAndCallbackOrder() {
        var fixture = new Fixture();
        fixture.Entries["WindowWidth"].OnChanged = value => {
            Equal("1000", fixture.Ini[("Setup", "WindowWidth")]);
            Equal(1000, value);
            fixture.Events.Add("changed");
        };
        Equal(1005, fixture.Engine.Get("WindowWidth"));
        Equal(634, fixture.Engine.Get("WindowHeight"));
        fixture.Engine.Set("WindowWidth", "1000");
        Sequence(new[] { "save:WindowWidth", "changed" }, fixture.Events);
        fixture.Ini[("Setup", "WindowWidth")] = "1200";
        Equal(1000, fixture.Engine.Get("WindowWidth"));
        string first = LegacySettingsCrypto.Encrypt("Alpha", "PCLsynthetic-device");
        string second = LegacySettingsCrypto.Encrypt("Beta", "PCLsynthetic-device");
        Equal("Alpha", fixture.Engine.GetCore("LoginLegacyName", null, _ => first));
        Equal("Beta", fixture.Engine.GetCore("LoginLegacyName", null, _ => second));
        Throws<InvalidOperationException>(() => fixture.Engine.SetSafe("LoginLegacyName", "Name"));
        Throws<KeyNotFoundException>(() => fixture.Engine.SetSafe("missing", "Name"));
        Equal(true, fixture.Engine.Get("UiHiddenPageLink"));
    }
